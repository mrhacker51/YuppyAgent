//! YuppyCode / Jarvis — native Linux desktop shell.
//!
//! Thin Tauri 2 window around the existing Next.js command centre (`ui/`).
//! The Rust backend stays exactly where it is: this shell supervises one
//! `yuppy bridge` child process and hands its authenticated, memory-only
//! connection info to the webview. No orchestration logic lives here.

// Prevents an extra console window on Windows in release builds.
#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]

mod sidecar;

use std::sync::Mutex;
use tauri::{Manager, RunEvent};

/// Bridge connection info shared with the webview through `bridge_config`.
/// The token is generated by this process, passed to the sidecar by env, and
/// only ever read back by the app's own webview — never written to
/// localStorage, never logged, never placed in a URL.
struct BridgeState(Mutex<Option<sidecar::BridgeHandle>>);

#[tauri::command]
fn bridge_config(state: tauri::State<'_, BridgeState>) -> Result<serde_json::Value, String> {
    let guard = state.0.lock().map_err(|e| e.to_string())?;
    Ok(match guard.as_ref() {
        Some(handle) => serde_json::json!({
            "url": handle.url,
            "token": handle.token,
            "spawned": true,
        }),
        None => serde_json::json!({
            "url": sidecar::DEFAULT_URL,
            "token": serde_json::Value::Null,
            "spawned": false,
        }),
    })
}

/// WebKitGTK's DMABUF/compositing path heap-corrupts ("free(): corrupted
/// unsorted chunks") on this Linux/GPU combination and takes the whole app
/// down mid-session. Force the software, non-compositing renderer before the
/// webview is created. Users can opt out by pre-setting any of these.
fn stabilise_webkit() {
    for (key, value) in [
        ("WEBKIT_DISABLE_DMABUF_RENDERER", "1"),
        ("WEBKIT_DISABLE_COMPOSITING_MODE", "1"),
        ("LIBGL_ALWAYS_SOFTWARE", "1"),
    ] {
        if std::env::var_os(key).is_none() {
            // SAFETY: single-threaded, before any thread or webview exists.
            unsafe { std::env::set_var(key, value) };
        }
    }
}

fn main() {
    stabilise_webkit();
    let app = tauri::Builder::default()
        .manage(BridgeState(Mutex::new(sidecar::spawn_bridge())))
        .invoke_handler(tauri::generate_handler![bridge_config])
        .build(tauri::generate_context!())
        .expect("failed to build the YuppyCode desktop app");
    app.run(|app, event| {
        if let RunEvent::Exit = event {
            // Belt and braces: the handle's Drop also kills the child, but
            // shutdown must never rely on drop timing.
            let state: tauri::State<BridgeState> = app.state();
            if let Ok(mut guard) = state.0.lock() {
                if let Some(handle) = guard.as_mut() {
                    handle.kill();
                }
            }
        }
    });
}
